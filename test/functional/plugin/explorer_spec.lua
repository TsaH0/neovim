-- Tests for the yazi-style file explorer (runtime/lua/vim/_core/explorer.lua).

local t = require('test.testutil')
local n = require('test.functional.testnvim')()

local describe, it, before_each, after_each = t.describe, t.it, t.before_each, t.after_each
local eq = t.eq
local feed = n.feed
local exec_lua = n.exec_lua

describe('file explorer', function()
  local dir
  before_each(function()
    n.clear()
    dir = t.tmpname(false)
    n.fn.mkdir(dir .. '/sub', 'p')
    t.write_file(dir .. '/sub/inner.txt', 'inner\n')
    t.write_file(dir .. '/b.txt', 'bee\n')
    t.write_file(dir .. '/a.txt', 'ay\n')
    t.write_file(dir .. '/.dot', '')
    exec_lua(function(d)
      require('vim._core.explorer').open(d)
    end, dir)
  end)
  after_each(function()
    n.fn.delete(dir, 'rf')
  end)

  local function listing()
    return n.api.nvim_buf_get_lines(0, 0, -1, true)
  end
  local function hovered()
    return n.api.nvim_get_current_line()
  end
  local function ls(d)
    local out = n.fn.readdir(d or dir)
    table.sort(out)
    return out
  end

  it('lists directories first, hides dotfiles; . toggles them', function()
    eq({ ' sub/', ' a.txt', ' b.txt' }, listing())
    feed('.')
    eq({ ' sub/', ' .dot', ' a.txt', ' b.txt' }, listing())
    feed('.')
  end)

  it('moves with j/k/G/gg, enters with l, goes up with h', function()
    feed('j')
    eq(' a.txt', hovered())
    feed('G')
    eq(' b.txt', hovered())
    feed('gg')
    eq(' sub/', hovered())
    feed('l')
    eq({ ' inner.txt' }, listing())
    feed('h')
    eq(' sub/', hovered())
  end)

  it('opens a file with l / <CR> and closes', function()
    feed('jl')
    t.matches('a%.txt$', n.api.nvim_buf_get_name(0))
    eq(false, exec_lua('return require("vim._core.explorer").is_open()'))
  end)

  it('creates files and directories (a), renames (r)', function()
    feed('anew.txt<CR>')
    feed('adir2/<CR>')
    eq({ '.dot', 'a.txt', 'b.txt', 'dir2', 'new.txt', 'sub' }, ls())
    eq(1, n.fn.isdirectory(dir .. '/dir2'))
    feed('G')
    eq(' new.txt', hovered())
    feed('r<C-u>renamed.txt<CR>')
    eq({ '.dot', 'a.txt', 'b.txt', 'dir2', 'renamed.txt', 'sub' }, ls())
  end)

  it('deletes with D (after confirmation)', function()
    feed('jD')
    feed('n<CR>')
    eq(true, n.fn.filereadable(dir .. '/a.txt') == 1)
    feed('Dy<CR>')
    eq({ '.dot', 'b.txt', 'sub' }, ls())
  end)

  it('selects with <Space>, yanks (y) and pastes (p) copies', function()
    feed('j<Space><Space>')
    feed('y')
    feed('ggl')
    feed('p')
    eq({ 'a.txt', 'b.txt', 'inner.txt' }, ls(dir .. '/sub'))
    feed('p')
    eq({ 'a.txt', 'a_1.txt', 'b.txt', 'b_1.txt', 'inner.txt' }, ls(dir .. '/sub'))
    eq(true, n.fn.filereadable(dir .. '/a.txt') == 1)
  end)

  it('cuts (x) and pastes (p) to move', function()
    feed('jx')
    feed('ggl')
    feed('p')
    eq({ 'a.txt', 'inner.txt' }, ls(dir .. '/sub'))
    eq(0, n.fn.filereadable(dir .. '/a.txt'))
  end)

  it('copies paths (cc), finds (/), filters (f), quits (q)', function()
    feed('jcc')
    eq(dir .. '/a.txt', n.fn.getreg('"'))
    feed('/b.t<CR>')
    eq(' b.txt', hovered())
    feed('fsu<CR>')
    eq({ ' sub/' }, listing())
    feed('<Esc>')
    eq({ ' sub/', ' a.txt', ' b.txt' }, listing())
    feed('q')
    eq(false, exec_lua('return require("vim._core.explorer").is_open()'))
  end)

  it('<Space>e opens it in Helix mode, at the workspace root', function()
    feed('q')
    n.fn.mkdir(dir .. '/.git', 'p')
    exec_lua(function(d)
      vim.o.helix = true
      vim.cmd.cd(d)
      vim.cmd.edit(d .. '/b.txt')
    end, dir)
    feed('<Space>e')
    eq(true, exec_lua('return require("vim._core.explorer").is_open()'))
    eq(' b.txt', hovered())
    feed('q<Space>.')
    eq(' b.txt', hovered())
    feed('q')
  end)
end)
