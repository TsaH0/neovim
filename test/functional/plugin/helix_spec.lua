      feed('lCC')
      eq({ { 0, 1, 0, 1 }, { 1, 1, 1, 1 }, { 2, 1, 2, 1 } }, sels())
      eq(3, primary())
      feed('iX<Esc>')
      eq({ 'aXbc', 'dXef', 'gXhi' }, lines())
      feed(',')
      eq(1, #sels())
      feed('ggw<M-C>')
