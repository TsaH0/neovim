      eq({ { 0, 4, 0, 0 } }, sels())
      feed('<M-:>')
      eq({ { 0, 0, 0, 4 } }, sels())
      feed(';')
      eq({ { 0, 4, 0, 4 } }, sels())
    end)

    it('( ) rotate primary, <M-(> <M-)> rotate contents, <M-,> removes primary', function()
      setup({ 'a b c' })
      feed('%s\\w<CR>')
      eq(3, primary())
      feed(')')
      eq(1, primary())
      feed('(')
      eq(3, primary())
      feed('<M-)>')
      eq({ 'c a b' }, lines())
      feed('<M-(>')
      eq({ 'a b c' }, lines())
      feed('<M-,>')
      eq({ 'a', 'b' }, texts())
    end)

    it('<M--> merges, <M-_> merges consecutive', function()
      setup({ 'a b c' })
      feed('%s\\w<CR><M-->')
      eq({ 'a b c' }, texts())
      setup({ 'abc' })
      feed('%s\\w<CR>')
      eq({ 'a', 'b', 'c' }, texts())
      feed('<M-_>')
      eq({ 'abc' }, texts())
    end)

    it('_ trims, & aligns', function()
      setup({ '  foo  ' })
      feed('%_')
      eq({ 'foo' }, texts())
