      eq({ { 0, 8, 0, 10 } }, sels())
    end)
    it('n in select mode adds selections', function()
      setup({ 'x foo foo foo' })
      feed('/foo<CR>vnn')
      eq({ 'foo', 'foo', 'foo' }, texts())
    end)
    it('? searches backward', function()
      setup({ 'foo bar foo' }, { 1, 10 })
      feed('?bar<CR>')
      eq({ { 0, 4, 0, 6 } }, sels())
    end)
    it('PCRE-style regex', function()
      setup({ 'a1 b22 c333' })
