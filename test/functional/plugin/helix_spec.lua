      feed('<M-C>')
      eq({ { 1, 0, 1, 0 }, { 2, 0, 2, 0 } }, sels())
    end)

    it('; <M-;> <M-:>', function()
      setup({ 'hello' })
      feed('e')
      eq({ { 0, 0, 0, 4 } }, sels())
