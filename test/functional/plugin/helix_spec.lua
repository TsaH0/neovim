      feed('%s=<CR>&')
      eq({ 'a  =1', 'bbb=2' }, lines())
    end)

    it('K / <M-K> keep/remove matching', function()
      setup({ 'foo', 'bar', 'baz' })
      feed('%<M-s>Kba<CR>')
      eq({ 'bar', 'baz' }, texts())
      feed('<M-K>z<CR>')
      eq({ 'bar' }, texts())
    end)

    it('X and <M-x> line bounds', function()
      setup({ 'abc', 'def' }, { 1, 1 })
